#!/usr/bin/env python3
"""Regenerate ForeverIconSearch/IconNames.lua from the wowdev community listfile.

Usage:
    python3 tools/build_icon_names.py                 # download latest listfile
    python3 tools/build_icon_names.py listfile.csv    # use a local copy

The listfile maps fileDataIDs to file paths. We keep only interface/icons/*,
strip the folder and extension, and emit one long Lua string ("id=name\n...")
that the addon parses lazily the first time a search runs.
"""
import io
import re
import sys
import urllib.request
from pathlib import Path

LISTFILE_URL = "https://github.com/wowdev/wow-listfile/releases/latest/download/community-listfile.csv"
OUT = Path(__file__).resolve().parent.parent / "ForeverIconSearch" / "IconNames.lua"
ICON_RE = re.compile(r"^(\d+);interface/icons/([^/]+)\.(?:blp|png|tga)$", re.IGNORECASE)


def iter_lines():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8", errors="replace") as fh:
            yield from fh
    else:
        print(f"Downloading {LISTFILE_URL} ...", file=sys.stderr)
        with urllib.request.urlopen(LISTFILE_URL) as resp:
            yield from io.TextIOWrapper(resp, encoding="utf-8", errors="replace")


def main():
    entries = {}
    for line in iter_lines():
        m = ICON_RE.match(line.strip())
        if m:
            entries[int(m.group(1))] = m.group(2).lower()

    body = "\n".join(f"{fid}={name}" for fid, name in sorted(entries.items()))
    if "]==]" in body:
        sys.exit("listfile contains ']==]', pick a different long-bracket level")

    OUT.write_text(
        "-- GENERATED by tools/build_icon_names.py from the wowdev community listfile. Do not edit.\n"
        "local _, ns = ...\n"
        f"ns.ICON_NAME_COUNT = {len(entries)}\n"
        "ns.ICON_NAME_DATA = [==[\n" + body + "\n]==]\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(entries)} icon names to {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
