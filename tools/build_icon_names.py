#!/usr/bin/env python3
"""Regenerate the addon's icon search data.

Writes two files into ForeverIconSearch/:

  IconNames.lua      fileDataID -> icon file name, from the wowdev community
                     listfile (interface/icons/* only).
  IconGameNames.lua  fileDataID -> names of every spell and item that uses the
                     icon, from the WoW: Forever game tables published on
                     wago.tools.

Both are emitted as one long Lua string that the addon parses lazily the
first time a search runs.

Usage:
    python3 tools/build_icon_names.py                       # download everything
    python3 tools/build_icon_names.py listfile.csv          # local listfile
    python3 tools/build_icon_names.py --db2-dir DIR         # local game-table CSVs
    python3 tools/build_icon_names.py --skip-listfile       # only game names
    python3 tools/build_icon_names.py --skip-game-names     # only file names
"""
import argparse
import collections
import csv
import io
import re
import sys
import urllib.request
from pathlib import Path

ADDON_DIR = Path(__file__).resolve().parent.parent / "ForeverIconSearch"
LISTFILE_URL = "https://github.com/wowdev/wow-listfile/releases/latest/download/community-listfile.csv"
DB2_URL = "https://wago.tools/db2/{table}/csv?product={product}"
DB2_TABLES = ("SpellName", "SpellMisc", "ItemSparse", "Item")
ICON_RE = re.compile(r"^(\d+);interface/icons/([^/]+)\.(?:blp|png|tga)$", re.IGNORECASE)
USER_AGENT = "ForeverIconSearch-build/1.0"


def log(msg):
    print(msg, file=sys.stderr)


def open_url(url):
    log(f"Downloading {url} ...")
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    return urllib.request.urlopen(req)


def write_lua(path, header, count_var, count, data_var, body):
    if "]==]" in body:
        sys.exit(f"{path.name}: data contains ']==]', pick a different long-bracket level")
    path.write_text(
        f"-- GENERATED by tools/build_icon_names.py from {header}. Do not edit.\n"
        "local _, ns = ...\n"
        f"ns.{count_var} = {count}\n"
        f"ns.{data_var} = [==[\n{body}\n]==]\n",
        encoding="utf-8",
    )
    log(f"Wrote {count} entries to {path}")


# --- Icon file names ---------------------------------------------------------

def build_file_names(listfile):
    if listfile:
        lines = open(listfile, encoding="utf-8", errors="replace")
    else:
        lines = io.TextIOWrapper(open_url(LISTFILE_URL), encoding="utf-8", errors="replace")

    entries = {}
    with lines:
        for line in lines:
            m = ICON_RE.match(line.strip())
            if m:
                entries[int(m.group(1))] = m.group(2).lower()

    body = "\n".join(f"{fid}={name}" for fid, name in sorted(entries.items()))
    write_lua(ADDON_DIR / "IconNames.lua", "the wowdev community listfile",
              "ICON_NAME_COUNT", len(entries), "ICON_NAME_DATA", body)


# --- Spell and item names ----------------------------------------------------

def read_table(table, db2_dir, product):
    csv.field_size_limit(sys.maxsize)
    if db2_dir:
        fh = open(Path(db2_dir) / f"{table}.csv", encoding="utf-8", newline="")
    else:
        fh = io.TextIOWrapper(open_url(DB2_URL.format(table=table, product=product)),
                              encoding="utf-8", newline="")
    with fh:
        yield from csv.DictReader(fh)


def clean(name):
    # One name per entry: no newlines, and '|' is our separator.
    return " ".join(name.replace("|", " ").split()).lower()


def build_game_names(db2_dir, product):
    spell_name = {int(r["ID"]): r["Name_lang"] for r in read_table("SpellName", db2_dir, product)}
    item_name = {int(r["ID"]): r["Display_lang"] for r in read_table("ItemSparse", db2_dir, product)}

    names = collections.defaultdict(set)
    for r in read_table("SpellMisc", db2_dir, product):
        icon, name = int(r["SpellIconFileDataID"] or 0), spell_name.get(int(r["SpellID"]))
        if icon and name:
            names[icon].add(clean(name))
    for r in read_table("Item", db2_dir, product):
        icon, name = int(r["IconFileDataID"] or 0), item_name.get(int(r["ID"]))
        if icon and name:
            names[icon].add(clean(name))

    body = "\n".join(f"{icon}={'|'.join(sorted(n for n in names[icon] if n))}"
                     for icon in sorted(names))
    write_lua(ADDON_DIR / "IconGameNames.lua", f"the WoW game tables ({product}) on wago.tools",
              "ICON_GAME_NAME_COUNT", len(names), "ICON_GAME_NAME_DATA", body)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("listfile", nargs="?", help="local community-listfile.csv (default: download)")
    p.add_argument("--db2-dir", help="directory with SpellName/SpellMisc/ItemSparse/Item .csv files (default: download)")
    p.add_argument("--product", default="wowf", help="wago.tools product to read game tables from (default: wowf)")
    p.add_argument("--skip-listfile", action="store_true")
    p.add_argument("--skip-game-names", action="store_true")
    args = p.parse_args()

    if not args.skip_listfile:
        build_file_names(args.listfile)
    if not args.skip_game_names:
        build_game_names(args.db2_dir, args.product)


if __name__ == "__main__":
    main()
